import assert from 'node:assert/strict';
import { chromium } from '../server/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: 'C:/Users/thuan/.agent-browser/browsers/chrome-153.0.8010.47/chrome.exe', headless: true });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/src/lib/editor/editorModelRegistry*', route => route.fulfill({ contentType: 'text/javascript', body: `export function acquireEditor(scope) { const provider = { scope, ready: true, snapshot: () => 0, subscribe: () => () => {} }; return { provider, release() {} }; }` }));
  await page.goto('http://localhost:5173/.evidence-review/collaboration-hook.html', { waitUntil: 'networkidle' });
  const expect = async value => page.waitForFunction(value => document.querySelector('output')?.textContent === value, value);
  await expect('No active provider');
  await page.getByRole('button', { name: 'Sign in A', exact: true }).click();
  await expect('user-a/project-a/snapshot-a/a.js');
  await page.getByRole('button', { name: 'Switch file', exact: true }).click();
  await expect('user-a/project-a/snapshot-a/b.js');
  await page.getByRole('button', { name: 'Disable', exact: true }).click();
  await expect('No active provider');
  await page.getByRole('button', { name: 'Enable', exact: true }).click();
  await expect('user-a/project-a/snapshot-a/b.js');
  await page.getByRole('button', { name: 'Switch project', exact: true }).click();
  await expect('user-a/project-b/snapshot-a/b.js');
  await page.getByRole('button', { name: 'Switch snapshot', exact: true }).click();
  await expect('user-a/project-b/snapshot-b/b.js');
  await page.getByRole('button', { name: 'Switch to B', exact: true }).click();
  await expect('user-b/project-b/snapshot-b/b.js');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect('No active provider');
  assert.equal(await page.getByLabel('Deferred draft').count(), 0);
  await page.getByRole('button', { name: 'Toggle deferred panel' }).click();
  await page.getByLabel('Deferred draft').fill('preserved draft');
  const mounts = await page.evaluate(() => window.deferredMounts);
  await page.getByRole('button', { name: 'Toggle deferred panel' }).click();
  await page.getByRole('button', { name: 'Toggle deferred panel' }).click();
  assert.equal(await page.getByLabel('Deferred draft').inputValue(), 'preserved draft');
  assert.equal(await page.evaluate(() => window.deferredMounts), mounts);
  const renders = await page.evaluate(() => window.hookRenders);
  assert.equal(renders.some(row => !row.enabled && row.identity !== 'No active provider'), false);
  assert.equal(renders.some(row => row.identity !== 'No active provider' && !row.identity.endsWith(`/${row.projectId}/${row.snapshotId}/${row.path}`)), false);
  assert.deepEqual(errors, []);
  console.log('PASS: real hook under StrictMode: initial auth loading, sign-in, file/project/snapshot changes, disabled feature, account switch and logout; no page errors. Registry mocked; no server data changed.');
} finally { await browser.close(); }
