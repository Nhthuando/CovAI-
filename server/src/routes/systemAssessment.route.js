import express from 'express';
import { authMiddleware } from '../middlewares/auth.middleware.js';
import { createAssessmentControllers } from '../controllers/systemAssessment.controller.js';
const router = express.Router();
const controllers = createAssessmentControllers();
router.use('/:snapshotId/system', authMiddleware);
const base = '/:snapshotId/system';
router.get(base + '/capabilities', controllers.capabilities);
router.get(base + '/assessments', controllers.latest);
router.post(base + '/assessments', controllers.assess);
router.get(base + '/assessments/:assessmentId', controllers.get);
router.get(base + '/requirements', controllers.requirements);
router.post(base + '/requirements', controllers.createRequirements);
router.post(base + '/requirements/:revisionId/confirm', controllers.confirmRequirements);
router.post(base + '/requirements/:revisionId/bindings', controllers.createBinding);
router.post(base + '/bindings/:bindingId/approve', controllers.approveBinding);
router.get(base + '/tests/analyze', controllers.analyze);
router.post(base + '/improvements', controllers.improve);
router.get(base + '/proposals/:proposalId', controllers.proposal);
router.post(base + '/proposals/:proposalId/apply', controllers.apply);
router.post(base + '/assessments/:assessmentId/mutations', controllers.mutate);
router.get(base + '/mutations/:mutationRunId', controllers.mutation);
export default router;
