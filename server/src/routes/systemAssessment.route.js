import { enforceProjectEndpointPolicy } from '../middlewares/projectEndpointPolicy.js';
import express from 'express';
import { authMiddleware } from '../middlewares/auth.middleware.js';
import { createAssessmentControllers } from '../controllers/systemAssessment.controller.js';
const router = express.Router();
router.use(authMiddleware, enforceProjectEndpointPolicy('coverage'));
const controllers = createAssessmentControllers();
router.use('/:snapshotId/system', authMiddleware);
const base = '/:snapshotId/system';
router.get(base + '/capabilities', controllers.capabilities);
router.get(base + '/catalog', controllers.catalog);
router.get(base + '/catalog/features', controllers.catalogFeatures);
router.post(base + '/catalog/sync', controllers.syncCatalog);
router.post(base + '/catalog/prepare', controllers.prepareCatalog);
router.post(base + '/catalog', controllers.createScenario);
router.post(base + '/catalog/:scenarioId/materialize', controllers.materializeScenario);
router.put(base + '/catalog/:scenarioId', controllers.updateScenario);
router.post(base + '/catalog/:scenarioId/confirm-expected', controllers.confirmScenarioExpected);
router.post(base + '/catalog/:scenarioId/review', controllers.reviewScenario);
router.get(base + '/readiness', controllers.readiness);
router.get(base + '/discovery', controllers.discovery);
router.get(base + '/assessments', controllers.latest);
router.post(base + '/assessments', controllers.assess);
router.get(base + '/assessments/:assessmentId', controllers.get);
router.get(base + '/assessments/:assessmentId/report.pdf', controllers.reportPdf);
router.get(base + '/assessments/:assessmentId/events', controllers.events);
router.get(base + '/assessments/:assessmentId/scenarios/:scenarioKey/evidence', controllers.scenarioEvidence);
router.get(base + '/artifacts/:artifactId', controllers.artifact);
router.get(base + '/requirements', controllers.requirements);
router.post(base + '/requirements', controllers.createRequirements);
router.post(base + '/requirements/:revisionId/confirm', controllers.confirmRequirements);
router.post(base + '/requirements/:revisionId/bindings', controllers.createBinding);
router.post(base + '/bindings/:bindingId/approve', controllers.approveBinding);
router.get(base + '/tests/analyze', controllers.analyze);
router.post(base + '/improvements', controllers.improve);
router.get(base + '/proposals', controllers.latestProposal);
router.get(base + '/proposals/:proposalId', controllers.proposal);
router.get(base + '/proposals/:proposalId/analyze', controllers.analyzeProposal);
router.post(base + '/proposals/:proposalId/review', controllers.reviewProposal);
router.post(base + '/proposals/:proposalId/apply', controllers.apply);
router.post(base + '/assessments/:assessmentId/mutations', controllers.mutate);
router.get(base + '/mutations/:mutationRunId', controllers.mutation);
export default router;
