import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import express from 'express';
import cors from 'cors';
import { chromium, expect } from '@playwright/test';
import { evaluationDatabase } from './helpers/aiEvaluationDatabase.mjs';
process.env.DATABASE_URL = '';
process.env.NODE_ENV = 'test';
process.env.AI_EVALUATION_ENABLED = 'true';
process.env.AI_EVALUATION_JUDGE_MODEL = '';
process.env.ENCRYPTION_KEY = '33'.repeat(32);
const { createEvaluationRouter } = await import('../routes/aiEvaluation.route.js');
const { processProjectEvaluation } = await import('../services/aiEvaluation/projectEvaluation.service.js');

test('project UI: one button checks imported chatbot, analyzes managed benchmark and shows results', { timeout: 240000 }, async () => {
    const database = await evaluationDatabase();
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'covai-project-browser-'));
    let http, vite, browser;
    try {
        await fs.writeFile(path.join(root, 'package.json'), JSON.stringify({ name: 'project-browser-fixture', version: '1.0.0', type: 'module', scripts: { start: 'node index.js' } }));
        await fs.writeFile(path.join(root, 'index.js'), `import http from 'node:http';
const routes=new Map(); const app={post:(path,handler)=>routes.set(path,handler)};
app.post('/chat',(req,res)=>{if(process.env.MODEL_TOKEN!=='browser-fixture-secret')throw new Error('Saved runtime configuration missing');const {messages}=req.body;const code=messages[0]?.content.match(/COVAI-[a-f0-9]+/)?.[0];res.json({answer:code||'I can answer questions about this application.'});});
http.createServer(async(req,res)=>{let body='';for await(const c of req)body+=c;try{const fn=routes.get(req.url);if(!fn){res.writeHead(404);res.end();return;}fn({body:JSON.parse(body)},{json:value=>{res.setHeader('Content-Type','application/json');res.end(JSON.stringify(value));}});}catch{res.writeHead(422);res.end('{}');}}).listen(Number(process.env.PORT)||3000,'0.0.0.0');`);
        const db = database.db;
        const user = await db.user.create({ data: { email: 'project-browser@evaluation.invalid' } });
        const project = await db.project.create({ data: { name: 'Imported chatbot', ownerId: user.id } });
        await db.projectSnapshot.create({ data: { projectId: project.id, source: 'GITHUB', storagePath: root, rootDir: root } });
        const jobs = [];
        const app = express(); app.use(cors()); app.use(express.json());
        app.use('/api/projects/:projectId/ai-evaluations', createEvaluationRouter({ db, auth: (req, _res, next) => { req.user = { id: user.id }; next(); }, enqueue: async (_type, id) => jobs.push(id) }));
        http = await new Promise(resolve => { const server = app.listen(0, '127.0.0.1', () => resolve(server)); });
        const { createServer } = await import('../../../client/node_modules/vite/dist/node/index.js');
        vite = await createServer({ root: fileURLToPath(new URL('../../../client', import.meta.url)), define: { 'import.meta.env.VITE_API_URL': JSON.stringify(`http://127.0.0.1:${http.address().port}/api`) }, server: { host: '127.0.0.1', port: 0, strictPort: false, hmr: false, open: false } }); await vite.listen();
        browser = await chromium.launch({ headless: true, ...(process.env.EVALUATION_BROWSER_CHANNEL ? { channel: process.env.EVALUATION_BROWSER_CHANNEL } : {}) });
        const page = await browser.newPage({ viewport: { width: 1280, height: 900 } }); page.setDefaultTimeout(20000);
        const errors = []; page.on('pageerror', error => errors.push(error.message));
        await page.addInitScript(token => localStorage.setItem('token', token), `test.${Buffer.from(JSON.stringify({ userId: user.id })).toString('base64')}.test`);
        await page.route('https://fonts.googleapis.com/**', route => route.abort());
        await page.goto(`http://127.0.0.1:${vite.httpServer.address().port}/e2e/trustworthiness.html?mode=project&projectId=${project.id}`);
        await expect(page.getByRole('button', { name: 'Evaluate Chatbot', exact: true })).toBeVisible();
        await expect(page.getByLabel('Endpoint HTTPS')).toHaveCount(0);
        await expect(page.getByLabel('New Benchmark Name')).toHaveCount(0);
        await page.getByText('Additional Configuration', { exact: true }).click();
        await page.getByLabel('Variable Name 1', { exact: true }).fill('MODEL_TOKEN');
        await page.getByLabel('Value 1', { exact: true }).fill('browser-fixture-secret');
        await page.getByRole('button', { name: 'Save Configuration', exact: true }).click();
        await expect(page.getByPlaceholder('Saved — leave blank to keep unchanged')).toBeVisible();
        await page.reload();
        await page.getByText('Additional Configuration', { exact: true }).click();
        await expect(page.getByLabel('Variable Name 1', { exact: true })).toHaveValue('MODEL_TOKEN');
        await expect(page.getByLabel('Value 1', { exact: true })).toHaveValue('');
        await expect(page.getByPlaceholder('Saved — leave blank to keep unchanged')).toBeVisible();
        assert.ok(!await page.evaluate(() => JSON.stringify(localStorage).includes('browser-fixture-secret')));
        await page.getByRole('button', { name: 'Evaluate Chatbot', exact: true }).click();
        await expect.poll(() => jobs.length).toBe(1);
        const sandbox = process.env.RUN_CHATBOT_SANDBOX_TEST === 'true' ? undefined : async () => ({ cleanup: async () => {}, request: async body => ({ status: 200, body: JSON.stringify({ answer: body.messages?.[0]?.content.match(/COVAI-[a-f0-9]+/)?.[0] || 'I can help with this application.' }) }) });
        await processProjectEvaluation(jobs[0], { db, ...(sandbox ? { sandbox } : {}) });
        await expect(page.getByRole('heading', { name: 'Evaluation Results', exact: true })).toBeVisible({ timeout: 20000 });
        await expect(page.getByText('✓ Chatbot started successfully and answered probe question.')).toBeVisible();
        await expect(page.getByText('Insufficient Evidence', { exact: true }).first()).toBeVisible();
        await expect(page.getByRole('button', { name: 'Evaluate Chatbot', exact: true })).toBeEnabled({ timeout: 10000 });
        const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download JSON' }).click(); assert.match((await download).suggestedFilename(), /\.json$/);
        await page.reload(); await expect(page.getByRole('heading', { name: 'Evaluation Results', exact: true })).toBeVisible();
        if (process.env.EVALUATION_SCREENSHOTS_DIR) { await fs.mkdir(process.env.EVALUATION_SCREENSHOTS_DIR, { recursive: true }); await page.screenshot({ path: path.join(process.env.EVALUATION_SCREENSHOTS_DIR, 'desktop.png'), fullPage: true }); }
        await page.setViewportSize({ width: 390, height: 844 }); await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'));
        await expect.poll(() => page.evaluate(() => getComputedStyle(document.body).backgroundColor)).toBe('rgb(11, 15, 20)');
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        if (process.env.EVALUATION_SCREENSHOTS_DIR) await page.screenshot({ path: path.join(process.env.EVALUATION_SCREENSHOTS_DIR, 'mobile-dark.png'), fullPage: true });
        await page.getByRole('button', { name: 'Delete Evaluation Run', exact: true }).click();
        await page.getByRole('button', { name: 'Delete', exact: true }).click();
        await expect(page.getByRole('heading', { name: 'Evaluation Results', exact: true })).toHaveCount(0);
        await expect.poll(() => db.aiEvaluationProjectRun.count({ where: { projectId: project.id } })).toBe(0);
        assert.equal(await db.aiEvaluationProjectSettings.count({ where: { projectId: project.id } }), 1, 'Deleting a run must retain the reusable project settings');
        assert.deepEqual(errors, []);
    } finally {
        await browser?.close(); await vite?.close(); if (http) await new Promise(resolve => http.close(resolve)); await database.close();
        assert.equal(path.dirname(path.resolve(root)), path.resolve(os.tmpdir())); assert.ok(path.basename(root).startsWith('covai-project-browser-')); await fs.rm(root, { recursive: true, force: true });
    }
});
