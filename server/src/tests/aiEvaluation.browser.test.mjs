import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import cors from 'cors';
import { chromium, expect } from '@playwright/test';
import { fileURLToPath } from 'node:url';
import { evaluationDatabase } from './helpers/aiEvaluationDatabase.mjs';
process.env.DATABASE_URL = '';
process.env.NODE_ENV = 'test';
process.env.AI_EVALUATION_ENABLED = 'true';
process.env.ENCRYPTION_KEY = '11'.repeat(32);
const { createEvaluationRouter } = await import('../routes/aiEvaluation.route.js');
const { processEvaluation } = await import('../services/aiEvaluation/runner.service.js');

test('minimal workspace creates target and benchmark, approves, evaluates and downloads report', { timeout: 120000 }, async () => {
    const database = await evaluationDatabase();
    let http, vite, browser;
    const jobs = [];
    try {
        const db = database.db;
        const owner = await db.user.create({ data: { email: 'browser@evaluation.invalid' } });
        const project = await db.project.create({ data: { name: 'Browser fixture', ownerId: owner.id } });
        const app = express(); app.use(cors()); app.use(express.json());
        app.use('/api/projects/:projectId/ai-evaluations', createEvaluationRouter({ db, auth: (req, res, next) => { req.user = { id: owner.id }; next(); }, enqueue: async (_type, jobId) => { jobs.push(jobId); } }));
        http = await new Promise(resolve => { const server = app.listen(0, '127.0.0.1', () => resolve(server)); });
        const { createServer } = await import('../../../client/node_modules/vite/dist/node/index.js');
        vite = await createServer({ root: fileURLToPath(new URL('../../../client', import.meta.url)), define: { 'import.meta.env.VITE_API_URL': JSON.stringify(`http://127.0.0.1:${http.address().port}/api`) }, server: { host: '127.0.0.1', port: 0, open: false } });
        await vite.listen();
        browser = await chromium.launch({ headless: true, ...(process.env.EVALUATION_BROWSER_CHANNEL ? { channel: process.env.EVALUATION_BROWSER_CHANNEL } : {}) });
        const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
        page.setDefaultTimeout(15000);
        const errors = []; page.on('pageerror', error => errors.push(error.message));
        await page.addInitScript(token => localStorage.setItem('token', token), `test.${Buffer.from(JSON.stringify({ userId: owner.id })).toString('base64')}.test`);
        await page.route('https://fonts.googleapis.com/**', route => route.abort());
        await page.goto(`http://127.0.0.1:${vite.httpServer.address().port}/e2e/trustworthiness.html?projectId=${project.id}`);
        await expect(page.getByRole('heading', { name: 'Chatbot Evaluation', exact: true })).toBeVisible();
        await page.getByLabel('Chatbot Name', { exact: true }).fill('Shop chatbot');
        await page.getByLabel('Endpoint HTTPS', { exact: true }).fill('https://chatbot.example.com/chat');
        await page.getByRole('button', { name: 'Save Chatbot', exact: true }).click();
        await page.getByRole('button', { name: '2. Benchmark', exact: true }).click();
        await page.getByLabel('New Benchmark Name').fill('Returns benchmark');
        await page.getByRole('button', { name: 'Create Benchmark', exact: true }).click();
        await page.getByRole('button', { name: 'Add Scenario', exact: true }).click();
        await page.getByLabel('Question / Turn 1', { exact: true }).fill('When can I return my order?');
        await page.getByLabel('Expected Behavior (for reviewer inspection)').fill('State the approved seven day return policy.');
        await page.getByLabel('Expected Answers / Required Points (one per line)').fill('7 days');
        await page.getByLabel('Minimum Passing Score (0–100)').fill('80');
        await page.getByLabel('I confirm the weights, passing threshold, and gating criteria for this benchmark.').check();
        await page.getByRole('button', { name: 'Approve Benchmark', exact: true }).click();
        await page.getByRole('button', { name: 'Save & Approve', exact: true }).click();
        await expect(page.getByRole('button', { name: 'Create New Draft' })).toBeVisible();
        await page.getByRole('button', { name: '3. Results', exact: true }).click();
        await page.getByLabel('Chatbot / Version').selectOption({ label: 'Shop chatbot · v1' });
        await page.getByLabel('Approved Benchmark').selectOption({ label: 'Returns benchmark · v1' });
        await page.getByRole('button', { name: 'Evaluate Chatbot', exact: true }).click();
        await expect.poll(() => jobs.length).toBe(1);
        await processEvaluation(jobs[0], { db, transport: async () => ({ answer: 'Returns within 7 days.' }) });
        await expect(page.getByText('100.0/100', { exact: false }).first()).toBeVisible({ timeout: 15000 });
        const download = page.waitForEvent('download');
        await page.getByRole('button', { name: 'Download JSON', exact: true }).click();
        assert.match((await download).suggestedFilename(), /chatbot-evaluation-.*\.json$/);
        await page.reload();
        await expect(page.getByRole('button', { name: 'Download JSON' })).toBeVisible();
        await page.setViewportSize({ width: 390, height: 844 });
        await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'));
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        assert.deepEqual(errors, []);
    } finally {
        await browser?.close(); await vite?.close();
        if (http) await new Promise(resolve => http.close(resolve));
        await database.close();
    }
});
