import crypto from 'crypto';
import { extractTestRequests } from './testSourceParser.service.js';
import {
    convertJestMocksAndStaticImportsToEsm,
    repairSupertestAppImport,
    resolveRelativeSpecifier,
} from './esmTestRepair.service.js';

/**
 * Supertest Post Processor Service
 * Processes raw AI output into validated Supertest integration test records.
 */

/**
 * Removes markdown code block wrappers from content.
 * @param {string} content
 * @returns {string}
 */
export const removeMarkdownWrappers = (content) => {
    if (!content) return "";
    let cleaned = content;
    cleaned = cleaned.replace(/^```(json|javascript|js|ts|typescript)?\s*/i, "");
    cleaned = cleaned.replace(/```\s*$/i, "");
    return cleaned.trim();
};

/**
 * Parses the raw text output from the AI into a JSON object.
 * @param {string} text
 * @returns {object|null}
 */
export const parseSupertestResponse = (text) => {
    if (!text) return null;
    try {
        const cleaned = removeMarkdownWrappers(text);
        const parsed = JSON.parse(cleaned);
        return parsed;
    } catch (e) {
        console.error("[SupertestPostProcessor] Failed to parse AI JSON:", e.message);
        return null;
    }
};

/**
 * Validates that the AI parsed output has the expected Supertest JSON structure.
 * @param {any} parsedData
 * @returns {{ valid: boolean, errors: string[] }}
 */
export const validateSupertestOutputFormat = (parsedData) => {
    const errors = [];

    if (!parsedData || typeof parsedData !== "object") {
        errors.push("Parsed AI data must be a JSON object.");
        return { valid: false, errors };
    }

    if (!parsedData.tests || !Array.isArray(parsedData.tests)) {
        errors.push('"tests" must be an array.');
        return { valid: false, errors };
    }

    if (parsedData.tests.length === 0) {
        errors.push("AI output contains no test files.");
        return { valid: false, errors };
    }

    return { valid: errors.length === 0, errors };
};

/**
 * Processes a single raw test entry from the AI output.
 * @param {{ filePath: string, content: string }} rawTest
 * @param {{ projectId: string, snapshotId: string }} context
 * @returns {object|null} Processed test record or null if invalid
 */
export const processSingleSupertestTest = (rawTest, { projectId, snapshotId }) => {
    if (!rawTest || !rawTest.filePath || !rawTest.content) {
        console.warn("[SupertestPostProcessor] Skipping test entry with missing filePath or content.");
        return null;
    }

    let content = rawTest.content.trim();
    if (!content.includes("[AI GENERATED]")) {
        content = `// [AI GENERATED] This Integration test was automatically generated by CovAI.\n\n${content}`;
    }

    const testBlocks = extractTestRequests(content, rawTest.filePath.trim());
    const requests = testBlocks.map(block => ({
        scenarioId: crypto.randomUUID(),
        testName: block.testName,
        suiteName: block.suiteName || "",
        enabled: true,
        userEdited: false,
        origin: "AI_GENERATED",
        method: block.method,
        path: block.path,
        ...(block.expectedStatus != null ? { expectedStatus: block.expectedStatus } : {}),
        ...(Array.isArray(block.expectedStatuses) && block.expectedStatuses.length > 0
            ? { expectedStatuses: block.expectedStatuses }
            : {}),
        line: block.line || 1,
        createdAt: new Date().toISOString()
    }));

    return {
        projectId,
        snapshotId,
        filePath: rawTest.filePath.trim(),
        mode: "FULL", // Persist as FULL to avoid Prisma enum errors
        content,
        metaJson: JSON.stringify({ framework: "SUPERTEST", status: "DRAFT", isValid: true, requests }),
    };
};

/**
 * Main orchestrator: parses AI response text, validates format,
 * and returns classified results.
 *
 * @param {string} responseText - Raw AI text response from Gemini
 * @param {{ projectId: string, snapshotId: string }} context
 * @returns {{ allTests: object[], summary: object }}
 */
export const processSupertestTests = (responseText, context) => {
    const parsedData = parseSupertestResponse(responseText);

    const validation = validateSupertestOutputFormat(parsedData);
    if (!validation.valid) {
        console.error("[SupertestPostProcessor] Validation failed:", validation.errors);
        throw new Error(`AI generated invalid Supertest format: ${validation.errors.join(" ")}`);
    }

    const allTests = [];
    const suggestions = [];

    // Process suggestions if they exist
    if (Array.isArray(parsedData.suggestions)) {
        for (const sug of parsedData.suggestions) {
            if (sug.filePath && sug.functionName) {
                suggestions.push({
                    projectId: context.projectId,
                    snapshotId: context.snapshotId,
                    filePath: sug.filePath.trim(),
                    functionName: sug.functionName.trim(),
                    priority: sug.priority || "HIGH",
                    message: sug.message ? sug.message.trim() : "Integration Test Scenario"
                });
            }
        }
    }

    const rawModuleType = context?.moduleType === "commonjs" || context?.moduleType === "esm"
        ? context.moduleType
        : null;
    const sourceCode = Array.isArray(context?.sourceCode) ? context.sourceCode : [];
    const rootDir = context?.rootDir || null;
    const backendSubdir = context?.backendSubdir ? String(context.backendSubdir).replace(/\\/g, "/").replace(/^\/+|\/+$/g, "") : "";

    for (const rawTest of parsedData.tests) {
        const processed = processSingleSupertestTest(rawTest, context);
        if (processed) {
            // Relocate root "tests/integration/..." into "<backendSubdir>/tests/integration/..." for monorepos
            if (backendSubdir && /^tests\/integration\//i.test(processed.filePath)) {
                processed.filePath = `${backendSubdir}/${processed.filePath}`;
            }

            let fileContent = processed.content;

            // Detect hybrid CJS/ESM when rawModuleType is unspecified
            const moduleType = rawModuleType || (
                /\brequire\s*\(\s*['"]/.test(fileContent) && !/from\s+['"]@jest\/globals['"]/.test(fileContent)
                    ? "commonjs"
                    : "esm"
            );

            if (moduleType === "commonjs") {
                // Target project uses CommonJS Jest: convert any ES module imports emitted by AI to require()
                fileContent = fileContent.replace(
                    /^\s*import\s+\{\s*jest[^}]*\}\s+from\s+['"]@jest\/globals['"];?\s*\r?\n?/gm,
                    ""
                );
                fileContent = fileContent.replace(
                    /^\s*import\s+(\w+)\s+from\s+(['"][^'"]+['"]);?/gm,
                    "const $1 = require($2);"
                );
                fileContent = fileContent.replace(
                    /^\s*import\s+\*\s+as\s+(\w+)\s+from\s+(['"][^'"]+['"]);?/gm,
                    "const $1 = require($2);"
                );
                fileContent = fileContent.replace(
                    /^\s*import\s+\{([^}]+)\}\s+from\s+(['"][^'"]+['"]);?/gm,
                    "const {$1} = require($2);"
                );
                fileContent = repairSupertestAppImport(fileContent, {
                    testFilePath: processed.filePath,
                    moduleType: "commonjs",
                    sourceCode,
                    rootDir,
                });
            } else {
                // ESM or default: convert stray CJS require('...') and fix app import / ESM mock hoisting
                if (fileContent.includes("require(")) {
                    fileContent = fileContent.replace(/const\s+(\w+)\s*=\s*require\(\s*(['"][^'"]+['"])\s*\)\s*;?/g, "import $1 from $2;");
                    fileContent = fileContent.replace(/const\s+\{([^}]+)\}\s*=\s*require\(\s*(['"][^'"]+['"])\s*\)\s*;?/g, "import { $1 } from $2;");
                }

                // Fix relative path depth (e.g. "../../server/src/index.js" -> "../../src/index.js") & compose routes if entry doesn't export app
                fileContent = repairSupertestAppImport(fileContent, {
                    testFilePath: processed.filePath,
                    moduleType: "esm",
                    sourceCode,
                    rootDir,
                });

                // Convert static local/mocked imports into `await import(...)` AFTER `await jest.unstable_mockModule(...)`
                // and auto-inject ESM Prisma / `@google/generative-ai` stubs if needed
                fileContent = convertJestMocksAndStaticImportsToEsm(fileContent, {
                    testFilePath: processed.filePath,
                    sourceCode,
                    rootDir,
                });

                // Ensure any leftover relative specifiers carry valid extensions
                fileContent = fileContent.replace(
                    /(\bimport\s*\(\s*)(['"])(\.[^'"]+)\2(\s*\))/g,
                    (m, p1, q, spec, p4) => `${p1}${q}${resolveRelativeSpecifier(spec, processed.filePath, sourceCode, rootDir)}${q}${p4}`
                );
            }

            // Re-extract requests from finalized file content so stored metadata stays accurate
            const finalizedBlocks = extractTestRequests(fileContent, processed.filePath);
            if (finalizedBlocks.length > 0) {
                const existingMeta = JSON.parse(processed.metaJson || "{}");
                const prevRequests = Array.isArray(existingMeta.requests) ? existingMeta.requests : [];
                existingMeta.requests = finalizedBlocks.map((block, idx) => ({
                    scenarioId: prevRequests[idx]?.scenarioId || crypto.randomUUID(),
                    testName: block.testName,
                    suiteName: block.suiteName || "",
                    enabled: true,
                    userEdited: false,
                    origin: "AI_GENERATED",
                    method: block.method,
                    path: block.path,
                    ...(block.expectedStatus != null ? { expectedStatus: block.expectedStatus } : {}),
                    ...(Array.isArray(block.expectedStatuses) && block.expectedStatuses.length > 0
                        ? { expectedStatuses: block.expectedStatuses }
                        : {}),
                    line: block.line || 1,
                    createdAt: prevRequests[idx]?.createdAt || new Date().toISOString(),
                }));
                processed.metaJson = JSON.stringify(existingMeta);
            }
            processed.content = fileContent;
            allTests.push(processed);
        }
    }

    const summary = {
        totalFiles: allTests.length,
        message: `Generated ${allTests.length} Supertest integration test file(s) and ${suggestions.length} scenarios.`
    };

    return { allTests, suggestions, summary };
};
