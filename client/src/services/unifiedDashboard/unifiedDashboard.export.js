import { fmtPct, fmtCount, fmtDuration, fmtRelativeTime } from "./format.js";

/**
 * Triggers a browser download of a generated string blob.
 */
function downloadBlob(content, filename, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 20000);
}

/**
 * Generates a clean technical Markdown report from UnifiedDashboardVM.
 */
export function generateMarkdownReport(vm) {
  const { context, qualityGate, health, execution, coverage, pillars, pyramid, matrix, actions, ai } = vm;

  const lines = [
    `# Unified Quality & Testing Report — ${context.projectName || "Project"}`,
    ``,
    `> **Snapshot ID:** \`${context.snapshotId || "N/A"}\``,
    `> **Generated:** ${new Date().toISOString()} (${fmtRelativeTime(context.updatedAt)})`,
    `> **Quality Gate Status:** **${qualityGate.label}** (${qualityGate.status})`,
    ``,
    `---`,
    ``,
    `## 1. Executive Summary`,
    ``,
    `- **Quality Health Score:** **${health.score ?? "—"}/100** (Grade ${health.grade ?? "—"})`,
    `- **Overall Test Execution:** ${fmtCount(execution.total)} tests run (${execution.passRate}% pass rate)`,
    `  - **Passed:** ${fmtCount(execution.passed)} | **Failed:** ${fmtCount(execution.failed)} | **Skipped:** ${fmtCount(execution.skipped)} | **Flaky:** ${fmtCount(execution.flaky)}`,
    `  - **Total Execution Duration:** ${fmtDuration(execution.durationMs)}`,
    `- **Multi-Layer Coverage Index:** ${fmtPct(coverage.overall)} average`,
    `  - **Code Coverage (Unit):** ${fmtPct(coverage.codePct)}`,
    `  - **API Endpoint Coverage (Integration):** ${fmtPct(coverage.apiPct)}`,
    `  - **User Flow Coverage (System E2E):** ${fmtPct(coverage.flowPct)}`,
    `- **AI Assistance & Coverage Gaps:** ${ai.aiGenerated} generated, ${ai.aiRepaired} repaired, ${ai.gaps} gaps remaining *(Demo Data)*`,
    ``,
    `### Quality Gate Condition Reasons`,
    ...(qualityGate.reasons || []).map((r) => `- ${r}`),
    ``,
    `---`,
    ``,
    `## 2. Testing Pyramid & Three Pillar Status`,
    ``,
    `**Pyramid Architecture:** \`${pyramid.shape.toUpperCase()}\`${pyramid.warning ? ` — *Warning: ${pyramid.warning}*` : ""}`,
    ``,
    `| Layer | Framework | Tests (P/F/Total) | Pass Rate | Coverage | Avg Latency | Source |`,
    `|---|---|---|---|---|---|---|`,
    `| **Unit Tests** | ${pillars.unit.framework} | ${pillars.unit.passedTests} / ${pillars.unit.failedTests} / ${pillars.unit.totalTests} | ${pillars.unit.passRate}% | Lines: ${fmtPct(pillars.unit.coverageMetrics?.lines)} (Branches: ${fmtPct(pillars.unit.coverageMetrics?.branches)}) | ${fmtDuration(pillars.unit.avgDurationMs)} | ${pillars.unit.source} |`,
    `| **Integration** | ${pillars.integration.framework} | ${pillars.integration.passedTests} / ${pillars.integration.failedTests} / ${pillars.integration.totalTests} | ${pillars.integration.passRate}% | API: ${fmtPct(pillars.integration.coverageMetrics?.apiEndpoint)} (Code: ${fmtPct(pillars.integration.coverageMetrics?.lines)}) | ${fmtDuration(pillars.integration.avgDurationMs)} | ${pillars.integration.source} |`,
    `| **System (E2E)** | ${pillars.system.framework} | ${pillars.system.passedTests} / ${pillars.system.failedTests} / ${pillars.system.totalTests} | ${pillars.system.passRate}% | Flow: ${fmtPct(pillars.system.coverageMetrics?.flow)} | ${fmtDuration(pillars.system.avgDurationMs)} | ${pillars.system.source} |`,
    ``,
    `---`,
    ``,
    `## 3. Cross-Layer Traceability Matrix *(Demo Data)*`,
    ``,
    `| Module | Unit Status | Integration Status | System Status | Diagnosis & Suspect Layer |`,
    `|---|---|---|---|---|`,
    ...(matrix.rows || []).map(
      (r) =>
        `| **${r.moduleName}** | ${r.unit.label} | ${r.integration.label} | ${r.system.label} | ${r.rootCause.summary} |`
    ),
    ``,
    `---`,
    ``,
    `## 4. Smart Action Center`,
    ``,
    ...(actions.items || []).map(
      (act, idx) =>
        `${idx + 1}. **[${act.priority}] ${act.title}** (${act.pillar.toUpperCase()})\n   - Target: \`${act.targetName}\`\n   - Description: ${act.description}`
    ),
    ``,
    `---`,
    ``,
    `*Report generated by CovAI Unified Quality & Testing Platform.*`,
  ];

  return lines.join("\n");
}

/**
 * Export full dashboard as formatted Markdown or JSON file.
 */
export function exportUnifiedDashboardReport(vm, format = "markdown") {
  const snapshotSlug = (vm.context?.snapshotId || "snapshot").slice(0, 8);
  const timestamp = new Date().toISOString().replace(/[:.]/g, "-");

  if (format === "json") {
    const filename = `covai-quality-report-${snapshotSlug}-${timestamp}.json`;
    const jsonStr = JSON.stringify(vm, null, 2);
    downloadBlob(jsonStr, filename, "application/json");
    return filename;
  }

  const filename = `covai-quality-report-${snapshotSlug}-${timestamp}.md`;
  const markdownStr = generateMarkdownReport(vm);
  downloadBlob(markdownStr, filename, "text/markdown");
  return filename;
}

export default exportUnifiedDashboardReport;
